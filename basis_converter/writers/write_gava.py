"""
writers/write_gava.py
Basis Set Converter — GAVA Text writer

Writes a GAVA text prior file from a list of core struct dicts, as VeSPA-Simulation writes one
(simulation/dialog_mixed_metabolite_output.py, _do_output_gava):

    ;comment lines, each starting with ';', ending with
    ;
    ;Simulation Spectral Results
    ;---------------------------------------------------------------------------
    abbr \\t dim1 \\t dim2 \\t dim3 \\t line_index \\t ppm \\t area \\t phase

joined by newlines, with no newline after the last row. Where:
    abbr       = metabolite name/abbreviation
    dim1/2/3   = the experiment's loop values, 0.0 for a single simulation (as VeSPA's floats)
    line_index = index of this line within the metabolite, from 0
    ppm        = the line's frequency, absolute ppm
    area       = its amplitude at t = 0, one scale for the whole set
    phase      = its phase in degrees

VeSPA-Simulation writes the same simulated ppms, areas and phases to GAVA, to MIDAS and to its
Analysis prior. So the lines are the VeSPA prior's (write_vespa.vespa_lines: each FID fitted
as undamped lines times the set's lineshape, phases in VeSPA's sign), written as VeSPA writes
numbers (str of a float). The comment names the source's file (not its folders) and states the
lineshape, the scale and the functions left out as broad humps.

Entry point:
    write_gava(basis_list, outpath, seqte, metablist_path, progress) -> .txt file
"""

import os
import textwrap
from datetime import datetime

if __name__ == '__main__':                    # run as a script: find the writers package
    import sys
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from writers.centre import CENTRE
from writers.lines import TOL
from writers.write_vespa import vespa_lines


def write_gava(basis_list, outpath,
               seqte=26.0,
               metablist_path=None,
               progress=None):
    """
    Write a GAVA text prior file.

    Parameters
    ----------
    basis_list     : list of core struct dicts
    outpath        : str, full path for output .txt file
    seqte          : float, echo time in ms
    metablist_path : str or None, unused (GAVA's lines hold no spin count)
    progress       : callable or None, progress(text, sub) once a metabolite's lines are fitted
                     or it is left out (write_vespa.vespa_lines)
    """
    outpath = os.path.abspath(outpath)
    os.makedirs(os.path.dirname(outpath) or '.', exist_ok=True)

    if not basis_list:
        raise RuntimeError("basis_list is empty")

    found = vespa_lines(basis_list, progress)
    now = datetime.now().strftime('%Y-%m-%dT%H:%M:%S')

    header = [
        'GAVA Text Prior generated by basis_set_converter',
        f'Created: {now}',
        f'Source: {source_name(basis_list)}',
    ] + simulation_comments(basis_list, found, seqte)
    # as VeSPA: the results heading, then every header line made a comment
    header += ['', 'Simulation Spectral Results', '-' * 75]
    lines = [';' + line for line in header]

    for name, rows, _ in found['metabolites']:
        for i, (ppm, area, phase) in enumerate(rows):
            lines.append('\t'.join([name, '0.0', '0.0', '0.0', str(i),
                                    str(ppm), str(area), str(phase)]))

    with open(outpath, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print(f"\n  Done. GAVA text: {os.path.basename(outpath)}")
    print(f"  {len(found['metabolites'])} of {len(basis_list)} metabolites  TE={seqte} ms")


def source_name(basis_list):
    """
    The file the set came from, as a GAVA or MIDAS header names it: the first function's file
    name without its folders, which would show the user's own folders in a file they may share.
    """
    source = basis_list[0].get('source')
    return os.path.basename(source) if source else 'unknown'


def simulation_comments(basis_list, found, seqte):
    """
    The comment lines of a GAVA or MIDAS prior, after its own first lines: the echo time and,
    in VeSPA-Simulation's sections, what the lines are and each metabolite's scale (1.0), shift
    (0.0) and ppm range. Neither format has a field for the lineshape or for functions left
    out, so the comment says them.
    """
    found_names = [name for name, _, _ in found['metabolites']]
    out = found['humps'] + found['skipped']
    text = (
        f"Lines: each FID fitted as undamped lines times the set's lineshape, "
        f"{found['lineshape']}: the fewest lines found that rebuild the FID to a relative "
        f"residual of {TOL:g} (from its second point). They are the lines of the VeSPA prior "
        f"written for the same set. Each line: ppm absolute (the set at {CENTRE} ppm), area its "
        f"amplitude at t = 0, phase in degrees, in Vespa-Simulation's sign (its FID is the "
        f"conjugate of the source's). Areas on the source's scale, the same for every "
        f"metabolite (factor 1: Scale=1.0 below). The lineshape is not in the lines: the fit's "
        f"lineshape is the data's whole lineshape." +
        (f" Rebuilt only to: {', '.join(found['short'])}." if found['short']
         else '') +
        (f" Left out, as broad humps that hold no line of the set's lineshape (sharp lines in "
         f"their place are wrong): {', '.join(found['humps'])}. Model them with the fit's own "
         f"macromolecule or baseline model." if found['humps'] else '') +
        (f" No lines found for: {', '.join(found['skipped'])}." if found['skipped'] else ''))

    lines = [f'TE: {float(seqte)} ms',
             f'Metabolites: {len(found_names)} of {len(basis_list)}' +
             (f' (left out: {", ".join(out)})' if out else ''),
             '', 'Output Comment', '-' * 75]
    lines += textwrap.wrap(text, 100)
    lines += ['', 'Metabolite Formatting Information', '-' * 75]
    for core in basis_list:
        if core.get('name', 'unknown') in found_names:
            half = float(core.get('sw') or 4000.0) / 2 / float(core.get('sf') or 123.26)
            lines.append(f"Name={core['name']} Abbr={core['name']} Scale=1.0 Shift=0.0 "
                         f"PPM Start={round(CENTRE - half, 3)} PPM End={round(CENTRE + half, 3)}")
    return lines


######################## Command line #######################

if __name__ == '__main__':
    import sys
    if len(sys.argv) < 3:
        print("Usage: python write_gava.py <input_folder> <output.txt> [te_ms]")
        sys.exit(1)

    from readers.read_marss import read_marss_file, read_marss_folder
    input_path     = sys.argv[1]
    outpath        = sys.argv[2]
    seqte          = float(sys.argv[3]) if len(sys.argv) > 3 else 26.0

    basis_list = read_marss_folder(input_path) if os.path.isdir(input_path) \
                 else [read_marss_file(input_path)]
    print(f"Loaded {len(basis_list)} metabolites\n")
    write_gava(basis_list, outpath, seqte=seqte)
